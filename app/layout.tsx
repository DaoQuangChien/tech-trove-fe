import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import { PropsWithChildren } from "react";

import { getCategories } from "@/lib/api/getCategories";
import { getGlobalConfig } from "@/lib/api/getGlobalConfig";
import { getLocales } from "@/lib/api/getLocales";

import "./globals.css";

import { Providers } from "./providers";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const revalidate = 300;

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

const RootLayout = async ({ children }: Readonly<PropsWithChildren>) => {
  const [globalConfig, categories, locales] = await Promise.all([
    getGlobalConfig(),
    getCategories(),
    getLocales(),
  ]);
  return (
    <html lang="en" suppressHydrationWarning>
      <body
        className={`${geistSans.variable} ${geistMono.variable} antialiased`}
        suppressHydrationWarning
      >
        <Providers globalConfigContext={{ globalConfig, categories, locales }}>
          {children}
        </Providers>
      </body>
    </html>
  );
};

export default RootLayout;
